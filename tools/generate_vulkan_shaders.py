#!/usr/bin/env python3
"""Compile NexaUI GLSL into embedded Vulkan 1.0 SPIR-V; no runtime compiler."""

import argparse
import hashlib
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail instead of replacing a stale header')
    parser.add_argument('--compiler', default='glslangValidator')
    parser.add_argument('--validator', default='spirv-val')
    args = parser.parse_args()
    for executable in (args.compiler, args.validator):
        if not shutil.which(executable):
            parser.error(f'{executable} is required to regenerate/verify shaders')
    root = Path(__file__).resolve().parents[1]
    shader_root = root / 'renderers' / 'vulkan'
    version = subprocess.check_output([args.compiler, '--version'], text=True).splitlines()[0]
    lines = ['/* Generated by tools/generate_vulkan_shaders.py; do not edit.',
             f'   {version}', '   Target: Vulkan 1.0 / SPIR-V 1.0. */',
             '#ifndef NEXAUI_VULKAN_SHADERS_H', '#define NEXAUI_VULKAN_SHADERS_H',
             '', '#include <stdint.h>', '']
    with tempfile.TemporaryDirectory(prefix='nexaui-shaders-') as temporary:
        for stage in ('vert', 'frag'):
            source = shader_root / 'shaders' / f'shape.{stage}'
            binary = Path(temporary) / f'shape.{stage}.spv'
            subprocess.run([args.compiler, '-V', '--target-env', 'vulkan1.0', '-o', str(binary),
                            str(source)], check=True)
            subprocess.run([args.validator, '--target-env', 'vulkan1.0', str(binary)], check=True)
            data = binary.read_bytes()
            if len(data) % 4 or len(data) < 20:
                raise ValueError('Invalid SPIR-V byte count')
            words = struct.unpack(f'<{len(data) // 4}I', data)
            if words[0] != 0x07230203 or words[1] != 0x00010000:
                raise ValueError('Shader must target SPIR-V 1.0')
            # Normalize checkout line endings for source provenance.
            digest = hashlib.sha256(source.read_text(encoding='utf-8').encode('utf-8')).hexdigest()
            lines += [f'/* shape.{stage} SHA-256: {digest} */',
                      f'static const uint32_t nx_vk_shape_{stage}[] = {{']
            for first in range(0, len(words), 8):
                lines.append('    ' + ', '.join(f'0x{word:08x}u' for word in words[first:first + 8]) + ',')
            lines += ['};', '']
    lines += ['#endif', '']
    output = '\n'.join(lines)
    header = shader_root / 'shaders.h'
    if args.check:
        if not header.exists() or header.read_text(encoding='utf-8') != output:
            parser.exit(1, 'Shader header differs. Use the recorded glslang version or regenerate and review.\n')
        print('Embedded shaders match source and pass spirv-val for Vulkan 1.0.')
    else:
        header.write_text(output, encoding='utf-8', newline='\n')
        print(f'Generated {header}')


if __name__ == '__main__':
    main()
