"""Embed the independent Vulkan lifetime control's SPIR-V (developer tool only)."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    parts = ['/* Generated by generate_vulkan_lifetime_shaders.py; Vulkan1.0. */\n',
             '#ifndef NEXAUI_VULKAN_LIFETIME_SHADERS_H\n#define NEXAUI_VULKAN_LIFETIME_SHADERS_H\n#include <stdint.h>\n']
    with tempfile.TemporaryDirectory(prefix='nexaui-lifetime-shaders-') as folder:
        for stage in ['vert', 'frag']:
            source = root/('vulkan_lifetime.'+stage)
            binary = Path(folder)/(stage+'.spv')
            subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0',
                            '-o', str(binary), str(source)], check=True)
            data = binary.read_bytes()
            if len(data) % 4 or data[:4] != b'\x03\x02\x23\x07':
                raise RuntimeError('Invalid SPIR-V output')
            parts.append('/* '+stage+' source SHA256 (LF): '+hashlib.sha256(source.read_text(encoding='utf-8').encode('utf-8')).hexdigest()+' */\n')
            parts.append('static const uint32_t lifetime_'+stage+'[] = {\n')
            words = struct.unpack('<'+'I'*(len(data)//4), data)
            for i in range(0, len(words), 8):
                parts.append('    '+', '.join('0x%08xu'%v for v in words[i:i+8])+',\n')
            parts.append('};\n')
    parts.append('#endif\n')
    output = ''.join(parts).encode('ascii')
    target = root/'vulkan_lifetime_shaders.h'
    if args.check:
        if not target.is_file() or target.read_text(encoding='ascii') != output.decode('ascii'):
            raise SystemExit('Embedded lifetime shaders differ from the selected system compiler')
    else:
        target.write_bytes(output)


if __name__ == '__main__':
    main()
