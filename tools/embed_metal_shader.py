#!/usr/bin/env python3
"""Embed authored MSL for Apple's OS compiler; this does not compile shaders."""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / 'renderers' / 'metal'
    source = (root / 'shape.metal').read_text(encoding='utf-8')
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    # Each literal stays below C17's 4095-character minimum. No runtime file I/O.
    lines = ['/* Generated by tools/embed_metal_shader.py; do not edit.',
             f'   shape.metal SHA-256: {digest}',
             '   Source embedding only; Apple Metal compilation is still required. */',
             '#ifndef NEXAUI_METAL_SHADER_SOURCE_H', '#define NEXAUI_METAL_SHADER_SOURCE_H',
             'static const char *const nx_mtl_shader_chunks[] = {']
    lines += ['    ' + json.dumps(source[i:i+1024], ensure_ascii=True) + ','
              for i in range(0, len(source), 1024)]
    output = '\n'.join(lines + ['};', '#endif', ''])
    header = root / 'shader_source.h'
    if args.check:
        if not header.exists() or header.read_text(encoding='utf-8') != output:
            parser.exit(1, 'Embedded Metal source is stale; regenerate with this script.\n')
        print('Embedded Metal source matches; no SDK compilation performed.')
    else:
        header.write_text(output, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
