#!/usr/bin/env python3
"""Embed the exact Shader Model 5.0 DXBC formerly compiled at first draw.

Generation and --check use Windows D3DCompiler_47 with flags 0, matching the
former runtime calls. --check-source verifies authored/embedded hashes on any OS.
"""
import argparse
import ctypes
import hashlib
import json
from pathlib import Path
import re
import struct
import sys


SHADERS = [('solid', 'nexaui-d3d12'), ('composite', 'nexaui-composite'),
           ('shape', 'nexaui-shape'), ('bitmap', 'nexaui-bitmap')]


def compile_shader(library, source, name, entry, target):
    function = library.D3DCompile
    function.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p,
                         ctypes.c_void_p, ctypes.c_void_p, ctypes.c_char_p,
                         ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                         ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    function.restype = ctypes.c_long
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()

    def method(blob, index, result_type):
        table = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
        return ctypes.WINFUNCTYPE(result_type, ctypes.c_void_p)(table[index])

    def data(blob):
        pointer = method(blob, 3, ctypes.c_void_p)(blob)
        length = method(blob, 4, ctypes.c_size_t)(blob)
        return ctypes.string_at(pointer, length)

    try:
        hr = function(source, len(source), name.encode('ascii'), None, None,
                      entry.encode('ascii'), target.encode('ascii'), 0, 0,
                      ctypes.byref(code), ctypes.byref(errors))
        if hr < 0:
            message = data(errors).decode(errors='replace') if errors else ''
            raise RuntimeError(f'D3DCompile {name}/{target}: {hr:#x}: {message}')
        if not code:
            raise RuntimeError('D3DCompile returned no bytecode')
        return data(code)
    finally:
        for blob in (errors, code):
            if blob:
                method(blob, 2, ctypes.c_ulong)(blob)


def validate_dxbc(data):
    if len(data) < 32 or data[:4] != b'DXBC' or struct.unpack_from('<I', data, 24)[0] != len(data):
        raise ValueError('Invalid embedded DXBC header/length')
    count = struct.unpack_from('<I', data, 28)[0]
    if count > 32 or 32+count*4 > len(data):
        raise ValueError('Invalid DXBC chunk table')
    for offset in struct.unpack_from(f'<{count}I', data, 32):
        if offset < 32+count*4 or offset+8 > len(data):
            raise ValueError('Invalid DXBC chunk offset')
        if offset+8+struct.unpack_from('<I', data, offset+4)[0] > len(data):
            raise ValueError('Invalid DXBC chunk size')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compile and compare every byte, without writing')
    parser.add_argument('--check-source', action='store_true', help='portable source/embedded integrity check; no compiler')
    args = parser.parse_args()
    folder = Path(__file__).resolve().parents[1]/'renderers/d3d12'
    header, manifest_path = folder/'shader_bytecode.h', folder/'shaders/manifest.json'
    if args.check_source:
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        embedded = header.read_text(encoding='utf-8')
        def require(condition, label):
            if not condition:
                raise ValueError('Embedded D3D12 integrity mismatch: '+label)
        require(manifest['target'] == 'Shader Model 5.0' and manifest['flags'] == [0, 0], 'target/flags')
        require(len(manifest['entries']) == 8, 'entry count')
        for entry in manifest['entries']:
            source = (folder/'shaders'/entry['source']).read_bytes()
            require(hashlib.sha256(source).hexdigest() == entry['source_sha256'], entry['source'])
            match = re.search(r'\b'+re.escape(entry['symbol'])+r'\[\]\s*=\s*\{([^}]+)\}', embedded)
            require(match is not None, entry['symbol'])
            bytecode = bytes(int(token, 16) for token in re.findall(r'0x([0-9a-f]{2})', match[1]))
            validate_dxbc(bytecode)
            require(len(bytecode) == entry['bytes'], entry['symbol']+' length')
            require(hashlib.sha256(bytecode).hexdigest() == entry['bytecode_sha256'], entry['symbol']+' digest')
        print('D3D12 sources and eight embedded DXBC blobs match their manifest; no compilation performed.')
        return
    if sys.platform != 'win32':
        parser.error('D3DCompiler_47 on Windows is required; use --check-source for portable integrity checks')
    library = ctypes.WinDLL('d3dcompiler_47.dll')
    lines = ['/* Generated by tools/generate_d3d12_shaders.py; do not edit.',
             '   D3DCompiler_47, Shader Model 5.0, flags 0. */',
             '#ifndef NEXAUI_D3D12_SHADER_BYTECODE_H', '#define NEXAUI_D3D12_SHADER_BYTECODE_H', '']
    entries = []
    for kind, name in SHADERS:
        source = (folder/'shaders'/f'{kind}.hlsl').read_bytes()
        for entry, target, suffix in [('VSMain', 'vs_5_0', 'vs'), ('PSMain', 'ps_5_0', 'ps')]:
            bytecode = compile_shader(library, source, name, entry, target)
            validate_dxbc(bytecode)
            symbol = f'nx_d3d12_{kind}_{suffix}'
            entries.append(dict(source=f'{kind}.hlsl', source_name=name, entry=entry, profile=target,
                                symbol=symbol, bytes=len(bytecode), source_sha256=hashlib.sha256(source).hexdigest(),
                                bytecode_sha256=hashlib.sha256(bytecode).hexdigest()))
            lines.append(f'static const unsigned char {symbol}[] = {{')
            lines.extend('    '+', '.join(f'0x{b:02x}' for b in bytecode[i:i+16])+',' for i in range(0, len(bytecode), 16))
            lines.extend(['};', ''])
    output = '\n'.join(lines+['#endif', ''])
    manifest = json.dumps(dict(target='Shader Model 5.0', compiler='D3DCompiler_47', flags=[0, 0], entries=entries), indent=2)+'\n'
    if args.check:
        if header.read_text(encoding='utf-8') != output or manifest_path.read_text(encoding='utf-8') != manifest:
            parser.exit(1, 'Embedded D3D12 bytecode differs; review the source/compiler change before regeneration.\n')
        print('All eight embedded DXBC blobs are byte-identical to D3DCompile(flags=0).')
    else:
        header.write_text(output, encoding='utf-8', newline='\n')
        manifest_path.write_text(manifest, encoding='utf-8', newline='\n')
        print('Embedded', sum(item['bytes'] for item in entries), 'DXBC bytes in eight static blobs.')


if __name__ == '__main__':
    main()
